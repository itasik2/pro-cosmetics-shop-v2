CREATE FUNCTION pg_temp.proofread_article_text(input_text TEXT)
RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $function$
DECLARE
    result TEXT := pg_temp.proofread_catalog_text(input_text);
BEGIN
    result := replace(result, 'трех', 'трёх');
    result := replace(result, 'Трех', 'Трёх');
    result := replace(result, 'Легкие', 'Лёгкие');
    result := replace(result, 'легкие', 'лёгкие');
    result := replace(result, 'Легкость', 'Лёгкость');
    result := replace(result, 'распространенное', 'распространённое');
    result := replace(result, 'утепленные', 'утеплённые');
    result := replace(result, 'расчесывайте', 'расчёсывайте');
    result := replace(result, 'пораженные', 'поражённые');
    result := regexp_replace(result, '\mеще\M', 'ещё', 'g');
    result := replace(
        result,
        'Однако, с правильным подходом и несколькими основными шагами, вы сможете создать эффективный и простой в использовании уходовый режим',
        'Однако при правильном подходе и соблюдении нескольких основных шагов вы сможете создать эффективную и понятную систему ухода'
    );
    result := replace(
        result,
        'Кожа на руках тоньше и более подвержена воздействиям.',
        'Кожа на руках тоньше и сильнее подвержена внешним воздействиям.'
    );
    result := replace(
        result,
        'Кремы с высоким содержанием жиров: кокосовое, оливковое, миндальное масла.',
        'Выбирайте кремы с питательными маслами: кокосовым, оливковым или миндальным.'
    );
    result := replace(
        result,
        'Мини-практика: выбирайте средства с непрерывным действием и обновляйте слой',
        'Мини-практика: выбирайте комфортное средство и обновляйте защитный слой'
    );
    result := replace(
        result,
        'может быть трудно управляемым',
        'может быть трудно контролировать'
    );
    result := replace(
        result,
        'локализованным проблемным зонам',
        'отдельным проблемным участкам'
    );
    result := replace(
        result,
        'Сильно пилинговать кожу безопасно.',
        'Интенсивно отшелушивать кожу безопасно.'
    );
    result := replace(result, 'как "гипоаллергенные"', 'как «гипоаллергенные»');
    result := replace(result, 'Средняя|', 'Средняя |');
    result := replace(result, ' - ключевые', ' — ключевые');
    result := replace(result, ' - лучший выбор', ' — лучший выбор');
    result := replace(result, ' - обязательный минимум', ' — обязательный минимум');
    result := replace(result, '? - ', '? — ');
    RETURN result;
END
$function$;

