    result := replace(result, 'Легкое', 'Лёгкое');
    result := replace(result, 'легкое', 'лёгкое');
    result := replace(result, 'легкой', 'лёгкой');
    result := replace(result, 'легкую', 'лёгкую');
    result := replace(result, 'Объем', 'Объём');
    result := replace(result, 'объем', 'объём');
    result := replace(result, 'мертвых', 'мёртвых');
    result := replace(result, 'придает', 'придаёт');
    result := replace(result, 'увлажненности', 'увлажнённости');
    result := replace(result, 'приближенный', 'приближённый');
    result := replace(result, 'подтвержденной', 'подтверждённой');
    result := replace(result, 'воспаленной', 'воспалённой');
    result := regexp_replace(result, '\mЕе\M', 'Её', 'g');
    result := regexp_replace(result, '\mее\M', 'её', 'g');
    result := replace(result, 'трех-шести', 'трёх–шести');
    result := replace(result, 'пленки', 'плёнки');
    result := replace(result, 'Теплым', 'Тёплым');
    result := replace(result, 'теплым', 'тёплым');
    result := replace(result, 'Теплой', 'Тёплой');
    result := replace(result, 'теплой', 'тёплой');
    result := replace(result, 'Теплую', 'Тёплую');
    result := replace(result, 'теплую', 'тёплую');
    result := replace(result, 'Теплое', 'Тёплое');
    result := replace(result, 'теплое', 'тёплое');
    result := replace(result, '30-60', '30–60');
    result := replace(result, '5-7', '5–7');
    result := replace(result, '4-6', '4–6');
    result := replace(result, '2-4', '2–4');
    result := replace(result, '2-3', '2–3');
    result := replace(result, '1-2', '1–2');
    result := replace(result, '5-10', '5–10');
    result := replace(result, 'SPF защитой', 'SPF-защитой');
    result := replace(result, 'SPF защиту', 'SPF-защиту');
    result := replace(result, 'SPF защита', 'SPF-защита');
    result := replace(result, '2%', '2 %');
    result := replace(result, '10%', '10 %');
    result := replace(result, ' Мл', ' мл');
    result := replace(result, ' Angiopharm – ', ' Angiopharm — ');
    result := replace(result, 'c HPR', 'с HPR');
    result := replace(result, 'Лифтинг сыворотка', 'Лифтинг-сыворотка');
    result := replace(result, 'аминокислотами шелка', 'аминокислотами шёлка');
    result := replace(result, 'АНА-Гель', 'АНА-гель');
    result := replace(result, 'сыворотку детокс-эффекта', 'сыворотку с детокс-эффектом');
    result := replace(result, 'Благодаря содержанию аминокислот, она', 'Благодаря содержанию аминокислот она');
    result := replace(result, 'избегая область вокруг глаз', 'избегая области вокруг глаз');
    result := replace(
        result,
        'представляет собой косметическое средство предназначенное',
        'представляет собой косметическое средство, предназначенное'
    );
    result := replace(result, 'в комплексный уход, благодаря', 'в комплексный уход благодаря');
    result := replace(result, '10 % азелаиновой кислоты указаны', '10 % азелаиновой кислоты указано');
    result := regexp_replace(
        result,
        '(Предупреждение:[[:space:]]*)?skin_type_not_confirmed[.]?',
        '',
        'gi'
    );
    result := regexp_replace(result, '[[:blank:]]+([,.;:!?])', '\1', 'g');
    result := regexp_replace(result, '[[:blank:]]{2,}', ' ', 'g');
    result := regexp_replace(result, E'\n[[:blank:]]*\n([[:blank:]]*\n)+', E'\n\n', 'g');
    RETURN btrim(result);
END
$function$;

