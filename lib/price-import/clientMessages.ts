export function priceImportFailureMessage(value: unknown) {
  const code = String(value || "");
  const messages: Record<string, string> = {
    default_brand_required_or_brand_column_missing:
      "Не удалось определить бренд. Укажите его в поле «Бренд по умолчанию» и загрузите файл повторно.",
    no_price_rows_found:
      "В PDF не найдена таблица с читаемыми ценами. Для скана потребуется распознавание текста или исходный Excel-файл.",
    ai_price_layout_uncertain:
      "ИИ не смог уверенно определить структуру таблицы. Укажите бренд или выберите подходящий шаблон.",
    ai_price_layout_invalid:
      "ИИ вернул неподтверждённую структуру. Цены не применены; повторите разбор.",
    ai_price_brand_unconfirmed:
      "Бренд, предложенный ИИ, не подтверждён файлом. Укажите бренд вручную.",
    ai_price_layout_conflict:
      "Предложенная ИИ структура противоречит заголовкам PDF. Проверьте файл или выберите шаблон.",
    pdf_table_layout_changed:
      "На страницах различается структура таблицы. Требуется проверка формата прайса.",
    pdf_table_layout_ambiguous:
      "В таблице несколько неоднозначных столбцов одного типа. Требуется уточнить структуру прайса.",
    pdf_table_row_incomplete:
      "Найдена строка с ценой без читаемого названия. Импорт остановлен для проверки PDF.",
    pdf_table_sku_invalid:
      "В колонке артикула обнаружены неоднозначные данные. Проверьте формат таблицы.",
    openai_not_configured:
      "Для анализа этого формата нужен настроенный ИИ. Проверьте подключение OpenAI или укажите бренд вручную.",
    openai_timeout:
      "ИИ не успел проанализировать структуру. Повторите загрузку или укажите бренд вручную.",
  };
  if (Object.prototype.hasOwnProperty.call(messages, code))
    return messages[code];
  if (/^openai_http_429/.test(code))
    return "Достигнут лимит ИИ. Повторите позже или укажите бренд вручную.";
  if (/^openai_/.test(code))
    return "ИИ не завершил анализ структуры. Повторите загрузку или укажите бренд вручную.";
  if (/^pdf_too_many_pages:/.test(code))
    return "В PDF слишком много страниц. Разделите прайс на файлы до 40 страниц.";
  return "Не удалось разобрать прайс. Проверьте PDF и повторите загрузку.";
}
