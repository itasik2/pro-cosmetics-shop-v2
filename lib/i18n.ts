/** Shared storefront language helpers. Never translate prices, IDs or SKU. */
export type SiteLocale = "ru" | "kk" | "en";
export const SITE_LOCALES = ["ru", "kk", "en"] as const;
export const SITE_LOCALE_COOKIE = "site_locale";

export function parseSiteLocale(value: unknown): SiteLocale {
  return value === "kk" || value === "en" ? value : "ru";
}

export function localeInPath(pathname: string): SiteLocale | null {
  const match = /^\/(kk|en)(?=\/|$)/.exec(pathname);
  return match ? parseSiteLocale(match[1]) : null;
}

export function stripLocale(pathname: string) {
  const normalized = pathname.startsWith("/") ? pathname : "/" + pathname;
  return normalized.replace(/^\/(?:kk|en)(?=\/|$)/, "") || "/";
}

export function isLocalizablePath(pathname: string) {
  const path = stripLocale(pathname);
  return path === "/" ||
    /^\/(?:shop|brand|blog|care|delivery|about|contacts|ask|requisites|checkout)(?:\/|$)/.test(path);
}

export function localizedHref(value: string, locale: SiteLocale) {
  if (!value.startsWith("/") || value.startsWith("//")) return value;
  const indices = [value.indexOf("#"), value.indexOf("?")].filter((n) => n >= 0);
  const cut = indices.length ? Math.min(...indices) : value.length;
  const pathname = value.slice(0, cut);
  if (!isLocalizablePath(pathname)) return value;
  const bare = stripLocale(pathname);
  const localized = locale === "ru" ? bare : "/" + locale + (bare === "/" ? "" : bare);
  return localized + value.slice(cut);
}

